def render_json(findings: list[dict], metadata: dict, output_path: Path) -> Path:
    """Render gap_findings.json (machine-readable)."""
    counts = _severity_counts(findings)
    dim_counts = {"D1": 0, "D2": 0, "D3": 0, "D4": 0}
    for f in findings:
        dim_counts[f["dimension"]] = dim_counts.get(f["dimension"], 0) + 1

    sev_label = {"🔴": "critical", "🟡": "moderate", "🟢": "minor"}
    bundle = {
        "metadata": metadata,
        "source_a": metadata.get("source_a_detail", {"identity": metadata.get("source_a_identity", "")}),
        "source_b": metadata.get("source_b_detail", {"identity": metadata.get("source_b_identity", "")}),
        "gaps": findings,
        "summary": {
            "total_gaps": len(findings),
            "by_severity": {sev_label[k]: v for k, v in counts.items()},
            "by_dimension": dim_counts,
        },
    }
    output_path.write_text(json.dumps(bundle, indent=2, default=str, ensure_ascii=False))
    return output_path


# ============================================================
# Bundle Orchestrator
# ============================================================

def render_bundle(findings: list[dict], metadata: dict,
                  output_dir: Path | str | None = None) -> dict[str, Path]:
    """Render semua 4 artefak. Return paths dict."""
    if output_dir is None:
        ts = datetime.now().strftime("%Y%m%d_%H%M%S")
        output_dir = Path(f"gap_analysis_output_{ts}")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "charts").mkdir(exist_ok=True)

    paths = {
        "markdown": render_markdown_report(findings, metadata, output_dir / "gap_analysis_report.md"),
        "xlsx": render_xlsx(findings, metadata, output_dir / "gap_analysis_workbook.xlsx"),
        "pdf": render_pdf(findings, metadata, output_dir / "gap_analysis_executive.pdf",
                          charts_dir=output_dir / "charts"),
        "json": render_json(findings, metadata, output_dir / "gap_findings.json"),
    }
    return paths


