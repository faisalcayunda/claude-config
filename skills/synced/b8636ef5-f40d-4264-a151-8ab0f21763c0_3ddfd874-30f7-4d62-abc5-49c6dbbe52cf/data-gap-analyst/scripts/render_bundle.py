def render_markdown_report(findings: list[dict], metadata: dict, output_path: Path) -> Path:
    """Render gap_analysis_report.md."""
    md = []
    md.append(f"---\ntitle: \"Gap Analysis Report — {metadata.get('case', 'Unnamed')}\"\n---\n")
    md.append(f"# Gap Analysis Report: {metadata.get('case', 'Unnamed')}\n")
    md.append(_render_meta_block(metadata))
    md.append("\n## Table of Contents\n")
    md.append("\n".join([
        "1. Executive Summary",
        "2. Scope & Method",
        "3. Input Inventory",
        "4. D1 — Volume & Completeness Gap",
        "5. D2 — Schema & Structural Gap",
        "6. D3 — Value Distribution & Semantic Gap",
        "7. D4 — Temporal & Freshness Gap",
        "8. Layer 1 Insight — Tim Data",
        "9. Layer 2 Insight — Stakeholder Bisnis",
        "10. Recommendations Matrix",
        "11. Appendix — Raw Metrics",
        "12. Schema Comparison Diagram",
    ]))

    md.append("\n\n---\n\n## 1. Executive Summary\n")
    md.append(_render_executive_summary(findings))

    md.append("\n## 2. Scope & Method\n")
    md.append(_render_scope_method(metadata))

    md.append("\n## 3. Input Inventory\n")
    md.append(_render_inventory(metadata))

    # Per dimensi
    for dim, title in [("D1", "Volume & Completeness"),
                       ("D2", "Schema & Structural"),
                       ("D3", "Value Distribution & Semantic"),
                       ("D4", "Temporal & Freshness")]:
        md.append(f"\n## {dim} — {title} Gap\n")
        dim_findings = [f for f in findings if f["dimension"] == dim]
        if not dim_findings:
            md.append("_Tidak ada gap finding untuk dimensi ini._\n")
        else:
            for f in dim_findings:
                md.append(_render_finding_full(f))

    md.append("\n## 8. Layer 1 Insight — Tim Data\n")
    md.append(_render_layer_summary(findings, layer=1))

    md.append("\n## 9. Layer 2 Insight — Stakeholder Bisnis\n")
    md.append(_render_layer_summary(findings, layer=2))

    md.append("\n## 10. Recommendations Matrix\n")
    md.append(_render_recommendations_table(findings))

    md.append("\n## 11. Appendix — Raw Metrics\n")
    md.append(_render_appendix(findings))

    md.append("\n## 12. Schema Comparison Diagram\n")
    md.append(_render_mermaid_schema(metadata))

    md.append("\n\n---\n\n*Generated by `data-gap-analyst` v1.0.0 — IDEAS skill ecosystem.*\n")

    output_path.write_text("\n".join(md), encoding="utf-8")
    return output_path


def _render_meta_block(meta: dict) -> str:
    return (
        f"**Source A**: `{meta.get('source_a_identity', '?')}`\n\n"
        f"**Source B**: `{meta.get('source_b_identity', '?')}`\n\n"
        f"**Mode**: {meta.get('mode_source_a', '?')}/{meta.get('mode_source_b', '?')}\n\n"
        f"**Business Entity**: {meta.get('business_entity', '?')}\n\n"
        f"**Tujuan**: {meta.get('purpose', '?')}\n\n"
        f"**Tanggal Profiling**: {meta.get('generated_at', '?')}\n\n"
        f"**Threshold Rubric**: {meta.get('threshold_rubric', 'default')}\n"
    )


def _render_executive_summary(findings: list[dict]) -> str:
    counts = _severity_counts(findings)
    lines = [
        f"Ditemukan **{len(findings)} gap findings**. Distribusi severity: "
        f"🔴 Critical ({counts['🔴']}), 🟡 Moderate ({counts['🟡']}), 🟢 Minor ({counts['🟢']}).",
        "",
        "Temuan utama yang butuh keputusan pimpinan:",
        "",
    ]
    top = sorted(findings, key=lambda f: _severity_rank(f["severity"]), reverse=True)[:5]
    for i, f in enumerate(top, 1):
        lines.append(f"{i}. {f['severity']} **{f.get('gap_id', '?')}** — {f.get('observation', f.get('context', ''))[:120]}")
    return "\n".join(lines)


def _render_scope_method(meta: dict) -> str:
    return (
        f"- **Source A** ({meta.get('mode_source_a', '?')}): {meta.get('source_a_identity', '?')}\n"
        f"- **Source B** ({meta.get('mode_source_b', '?')}): {meta.get('source_b_identity', '?')}\n"
        f"- **Threshold rubric**: {meta.get('threshold_rubric', 'default')} "
        f"({'override aktif' if meta.get('threshold_override') else 'tidak ada override'})\n"
        f"- **Tools**: `scripts/profile_source.py`, `scripts/compute_gap.py`, "
        f"`scripts/llm_reasoning_helper.py`, `scripts/render_bundle.py`\n"
    )


def _render_inventory(meta: dict) -> str:
    table_map = meta.get("table_mapping", [])
    if not table_map:
        return "_Inventory belum dipopulate — cek metadata input._\n"
    lines = ["### Tabel Mapping\n", "| Source A | Source B | Match Type | Catatan |", "|---|---|---|---|"]
    for m in table_map:
        lines.append(
            f"| `{m.get('a', '-')}` | `{m.get('b', '-')}` | {m.get('match_type', '-')} | {m.get('note', '')} |"
        )
    return "\n".join(lines)


def _render_finding_full(f: dict) -> str:
    """Render finding lengkap dengan 7-step reasoning chain."""
    out = [
        f"\n### Gap {f.get('gap_id', '?')} — {f.get('title', f.get('context', 'Untitled'))}\n",
        f"**Severity**: {f['severity']} | **Confidence**: {f.get('confidence', 'medium')}\n",
    ]
    # Reasoning chain dalam narasi paragraf
    if "reasoning_chain" in f:
        rc = f["reasoning_chain"]
        for step_name in ["observation", "magnitude", "hypothesis", "evidence_test",
                          "conclusion", "impact", "recommendation"]:
            if step_name in rc:
                out.append(rc[step_name].strip() + "\n")
    else:
        # Fallback: render dari field flat
        out.append(f"**Observation**: {f.get('observation', f.get('context', '-'))}\n")
        if "magnitude" in f:
            out.append(f"**Magnitude**: {f['magnitude']}\n")
    return "\n".join(out)


def _render_layer_summary(findings: list[dict], layer: int) -> str:
    key = f"layer{layer}_text"
    lines = []
    for f in findings:
        text = f.get(key, "_[layer text belum di-generate]_")
        lines.append(f"### {f.get('gap_id', '?')} — {f['severity']}\n\n{text}\n")
    return "\n".join(lines)


def _render_recommendations_table(findings: list[dict]) -> str:
    lines = [
        "| Gap ID | Severity | Owner | Urgency | Action |",
        "|---|---|---|---|---|",
    ]
    for f in findings:
        lines.append(
            f"| {f.get('gap_id', '?')} | {f['severity']} | "
            f"{f.get('owner', '-')} | {f.get('urgency', '-')} | "
            f"{f.get('recommendation', '-')[:100]} |"
        )
    return "\n".join(lines)


def _render_appendix(findings: list[dict]) -> str:
    lines = ["Source trace per gap finding (verifikasi reproducibility):\n"]
    for f in findings:
        st = f.get("source_trace", {})
        lines.append(f"- **{f.get('gap_id', '?')}**: A=`{st.get('query_a', '-')}` | B=`{st.get('query_b', '-')}`")
    return "\n".join(lines)


def _render_mermaid_schema(meta: dict) -> str:
    """Mermaid classDiagram side-by-side schema comparison."""
    schema_a = meta.get("schema_a_classes", "  class SourceA {\n    +placeholder\n  }")
    schema_b = meta.get("schema_b_classes", "  class SourceB {\n    +placeholder\n  }")
    return f"```mermaid\nclassDiagram\n{schema_a}\n{schema_b}\n  SourceA --> SourceB : ETL transform\n```\n"


def _severity_counts(findings: list[dict]) -> dict:
    counts = {"🔴": 0, "🟡": 0, "🟢": 0}
    for f in findings:
        counts[f["severity"]] = counts.get(f["severity"], 0) + 1
    return counts


def _severity_rank(s: str) -> int:
    return {"🟢": 0, "🟡": 1, "🔴": 2}.get(s, 0)


