def render_xlsx(findings: list[dict], metadata: dict, output_path: Path) -> Path:
    """Render gap_analysis_workbook.xlsx (multi-sheet)."""
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Font, PatternFill, Alignment
        from openpyxl.formatting.rule import CellIsRule
    except ImportError:
        # Fallback: write CSV alternatives
        _render_xlsx_fallback_csv(findings, metadata, output_path)
        return output_path

    wb = Workbook()
    wb.remove(wb.active)

    # Sheet 1 — Cover
    s = wb.create_sheet("Cover")
    s["A1"] = "Gap Analysis Report"
    s["A1"].font = Font(size=18, bold=True)
    rows = [
        ("Source A", metadata.get("source_a_identity", "")),
        ("Source B", metadata.get("source_b_identity", "")),
        ("Mode", f"{metadata.get('mode_source_a', '')}/{metadata.get('mode_source_b', '')}"),
        ("Business Entity", metadata.get("business_entity", "")),
        ("Purpose", metadata.get("purpose", "")),
        ("Generated At", metadata.get("generated_at", "")),
        ("Total Gaps", str(len(findings))),
    ]
    for i, (k, v) in enumerate(rows, start=3):
        s[f"A{i}"] = k
        s[f"B{i}"] = v
        s[f"A{i}"].font = Font(bold=True)

    # Sheet 2 — Executive Summary
    s = wb.create_sheet("Executive Summary")
    counts = _severity_counts(findings)
    s["A1"] = "Severity Distribution"
    s["A1"].font = Font(bold=True)
    for i, (sev, cnt) in enumerate(counts.items(), start=2):
        s[f"A{i}"] = sev
        s[f"B{i}"] = cnt

    # Sheet 3 — Schema Diff
    s = wb.create_sheet("Schema Diff")
    headers = ["Column A", "Type A", "Constraint A", "Column B", "Type B", "Constraint B", "Delta Flag"]
    for c, h in enumerate(headers, 1):
        s.cell(1, c, h).font = Font(bold=True)
    row = 2
    for f in findings:
        if f["dimension"] != "D2":
            continue
        s.cell(row, 1, f.get("context", ""))
        s.cell(row, 7, f["severity"])
        row += 1

    # Sheet 4 — Volume Diff
    s = wb.create_sheet("Volume Diff")
    headers = ["Context", "Value A", "Value B", "Delta Abs", "Delta %", "Severity", "Gap ID"]
    for c, h in enumerate(headers, 1):
        s.cell(1, c, h).font = Font(bold=True)
    row = 2
    for f in findings:
        if f["dimension"] != "D1" or f.get("metric") != "row_count_diff":
            continue
        s.cell(row, 1, f.get("context", ""))
        s.cell(row, 2, f.get("value_a", ""))
        s.cell(row, 3, f.get("value_b", ""))
        s.cell(row, 4, f.get("absolute", ""))
        s.cell(row, 5, f.get("relative", ""))
        s.cell(row, 6, f["severity"])
        s.cell(row, 7, f.get("gap_id", ""))
        row += 1

    # Sheet 5 — Distribution Diff
    s = wb.create_sheet("Distribution Diff")
    headers = ["Column", "Mean A", "Mean B", "KS p-value", "Jaccard", "Severity"]
    for c, h in enumerate(headers, 1):
        s.cell(1, c, h).font = Font(bold=True)

    # Sheet 6 — Temporal Diff
    s = wb.create_sheet("Temporal Diff")
    headers = ["Context", "Max A", "Max B", "Lag (h)", "SLA (h)", "Severity"]
    for c, h in enumerate(headers, 1):
        s.cell(1, c, h).font = Font(bold=True)

    # Sheet 7 — Field-Level Gap Matrix
    s = wb.create_sheet("Gap Matrix")
    s["A1"] = "Field-level heatmap — see report markdown for full visualization"

    # Sheet 8 — Recommendations
    s = wb.create_sheet("Recommendations")
    headers = ["Gap ID", "Dimension", "Severity", "Recommendation", "Owner", "Urgency",
               "Layer 1 (excerpt)", "Layer 2 (excerpt)"]
    for c, h in enumerate(headers, 1):
        s.cell(1, c, h).font = Font(bold=True)
    for i, f in enumerate(findings, start=2):
        s.cell(i, 1, f.get("gap_id", ""))
        s.cell(i, 2, f["dimension"])
        s.cell(i, 3, f["severity"])
        s.cell(i, 4, f.get("recommendation", ""))
        s.cell(i, 5, f.get("owner", ""))
        s.cell(i, 6, f.get("urgency", ""))
        s.cell(i, 7, (f.get("layer1_text", "") or "")[:200])
        s.cell(i, 8, (f.get("layer2_text", "") or "")[:200])

    # Sheet 9 & 10 — Raw Metrics (placeholder)
    s = wb.create_sheet("Raw Metrics A")
    s["A1"] = "Source A raw metrics (populated dari profile JSON)"
    s = wb.create_sheet("Raw Metrics B")
    s["A1"] = "Source B raw metrics (populated dari profile JSON)"

    wb.save(output_path)
    return output_path


def _render_xlsx_fallback_csv(findings, metadata, output_path):
    """Fallback jika openpyxl tidak ter-install."""
    import csv
    csv_path = output_path.with_suffix(".csv")
    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["gap_id", "dimension", "severity", "context",
                                          "recommendation", "owner", "urgency"])
        w.writeheader()
        for finding in findings:
            w.writerow({k: finding.get(k, "") for k in w.fieldnames})


