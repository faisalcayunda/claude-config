def render_pdf(findings: list[dict], metadata: dict, output_path: Path,
               charts_dir: Path | None = None) -> Path:
    """Render gap_analysis_executive.pdf (3-5 halaman polished)."""
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.units import cm
        from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Image,
                                        PageBreak, Table, TableStyle)
        from reportlab.lib import colors
    except ImportError:
        # Fallback: tulis sebagai markdown saja
        md_path = output_path.with_suffix(".md")
        md_path.write_text(_render_pdf_fallback_md(findings, metadata))
        return md_path

    doc = SimpleDocTemplate(str(output_path), pagesize=A4,
                            topMargin=2*cm, bottomMargin=2*cm,
                            leftMargin=2*cm, rightMargin=2*cm)
    styles = getSampleStyleSheet()
    h1 = ParagraphStyle("H1", parent=styles["Heading1"], fontSize=24, spaceAfter=20)
    h2 = ParagraphStyle("H2", parent=styles["Heading2"], fontSize=16, spaceAfter=12)
    body = ParagraphStyle("Body", parent=styles["BodyText"], fontSize=10, leading=14)

    story = []

    # Halaman 1 — Cover
    story.append(Spacer(1, 5*cm))
    story.append(Paragraph("GAP ANALYSIS REPORT", h1))
    story.append(Paragraph(metadata.get("case", ""), h2))
    story.append(Spacer(1, 2*cm))
    counts = _severity_counts(findings)
    story.append(Paragraph(
        f"🔴 {counts['🔴']} Critical &nbsp;&nbsp; 🟡 {counts['🟡']} Moderate &nbsp;&nbsp; 🟢 {counts['🟢']} Minor",
        body
    ))
    story.append(Spacer(1, 2*cm))
    story.append(Paragraph(f"Generated: {metadata.get('generated_at', '')}", body))
    story.append(Paragraph("By: data-gap-analyst v1.0.0", body))
    story.append(PageBreak())

    # Halaman 2 — Executive Summary (Layer 2)
    story.append(Paragraph("Executive Summary", h2))
    story.append(Paragraph(_render_executive_summary(findings).replace("\n", "<br/>"), body))

    # Embed charts jika ada
    if charts_dir and charts_dir.exists():
        for chart_name in ["chart_volume_diff.png", "chart_null_heatmap.png"]:
            cp = charts_dir / chart_name
            if cp.exists():
                story.append(Spacer(1, 0.5*cm))
                story.append(Image(str(cp), width=15*cm, height=7*cm))
    story.append(PageBreak())

    # Halaman 3 — Top 3 Critical Findings (Layer 2 narrative)
    story.append(Paragraph("Top Findings — Untuk Pimpinan", h2))
    top = sorted(findings, key=lambda f: _severity_rank(f["severity"]), reverse=True)[:3]
    for f in top:
        story.append(Paragraph(
            f"<b>{f['severity']} {f.get('gap_id', '?')}</b>",
            body
        ))
        story.append(Paragraph(f.get("layer2_text", "")[:1000], body))
        story.append(Spacer(1, 0.5*cm))
    story.append(PageBreak())

    # Halaman 4 — Visual Summary (charts)
    if charts_dir and charts_dir.exists():
        story.append(Paragraph("Visual Summary", h2))
        for chart_name in ["chart_distribution_overlay.png", "chart_temporal_lag.png",
                           "chart_severity_donut.png"]:
            cp = charts_dir / chart_name
            if cp.exists():
                story.append(Image(str(cp), width=15*cm, height=7*cm))
                story.append(Spacer(1, 0.3*cm))
        story.append(PageBreak())

    # Halaman 5 — Recommendations untuk Pimpinan
    story.append(Paragraph("Recommendations untuk Pimpinan", h2))
    recs_data = [["Gap ID", "Severity", "Recommendation", "Urgency"]]
    for f in findings:
        recs_data.append([
            f.get("gap_id", ""),
            f["severity"],
            (f.get("recommendation", ""))[:80],
            f.get("urgency", ""),
        ])
    tbl = Table(recs_data, colWidths=[2*cm, 2*cm, 10*cm, 2.5*cm])
    tbl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
    ]))
    story.append(tbl)

    doc.build(story)
    return output_path


def _render_pdf_fallback_md(findings: list[dict], metadata: dict) -> str:
    """Fallback markdown jika reportlab tidak ter-install."""
    return (
        f"# Gap Analysis Executive (Fallback MD)\n\n"
        f"Metadata: {json.dumps(metadata, indent=2)}\n\n"
        f"Total findings: {len(findings)}\n\n"
        f"_PDF rendering tidak tersedia — install `reportlab` untuk PDF binary._\n"
    )


