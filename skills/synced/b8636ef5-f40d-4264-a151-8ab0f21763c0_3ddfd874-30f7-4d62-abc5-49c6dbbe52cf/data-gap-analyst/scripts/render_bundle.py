"""
render_bundle.py — Render 4 artefak output bundle.
Bagian dari skill `data-gap-analyst`.

Input: list gap findings (dengan reasoning chain dari llm_reasoning_helper.py)
       + Source A/B identity + metadata.

Output (di folder gap_analysis_output_<timestamp>/):
    - gap_analysis_report.md       (Docusaurus-ready)
    - gap_analysis_workbook.xlsx   (multi-sheet, conditional formatting)
    - gap_analysis_executive.pdf   (3-5 halaman polished)
    - gap_findings.json            (machine-readable)
    - charts/*.png                 (3-6 chart untuk embedded di PDF)

Anti-halusinasi: render setiap angka dengan footnote source_trace.
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any


